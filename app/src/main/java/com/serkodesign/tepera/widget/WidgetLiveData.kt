package com.serkodesign.tepera.widget

import kotlinx.coroutines.flow.MutableStateFlow

/**
 * Живі дані віджетів. **Причина, з якої це існує (знайдено на Samsung S23):** раніше `provideGlance()`
 * завантажував усе (таймери, категорії, записи) ОДИН РАЗ на початку сесії Glance, а сесія живе ще деякий час після
 * оновлення — наступні `update()` лише перекомпоновували той самий знімок. Наслідки: другий і далі тап показував
 * застарілий стан кнопок, а два екземпляри віджета (окремі сесії різного віку) розходились між собою.
 *
 * Тепер таймери/категорії/записи — потоки (`collectAsState`) усередині композиції, тож будь-яка жива сесія оновлюється
 * сама, щойно змінюється сховище; важкі частини (Online, вікна) перераховуються, коли піднімається [refreshTick].
 */
object WidgetLiveData {
    /** Піднімається [forceRefresh]; сесії залежать від нього й перераховують важку частину. */
    val refreshTick = MutableStateFlow(0L)

    /** Піднімається після власних дій віджетів-дій (ActionWidgets.kt) — їхні сесії перечитують дані, не чіпаючи важкі Online-розрахунки. */
    val actionTick = MutableStateFlow(0L)

    fun forceRefresh() {
        refreshTick.value++
    }
}
