package com.serkodesign.tepera.data.cards

/**
 * T-13, рівень 1 "джерело картки". [priority] — нижче значення = вищий пріоритет (той самий
 * порядок, що раніше жив у `ContextCardStack.kt`). [minIntervalDays] — мінімальний інтервал
 * повтору для ЦЬОГО типу, перевіряється рушієм проти останнього [CardResult.ANSWERED]/
 * [CardResult.SKIPPED] запису в історії; `null` означає, що рушій не накладає власного інтервалу
 * — картка сама відповідає за власну готовність (напр. `PatternMiniCard`, чия "частота" — просто
 * "показувати завжди, коли розблокована" плюс власний ключ закриття "до завтра", не керований
 * цим рушієм). [dataReady] — чи є в картки зараз що показати (рахує викликач із стану відповідної
 * ViewModel, рушій цього не знає й не повинен знати — розмежування з розділу 2 документа
 * "вимоги до даних" належать джерелу, не рушію).
 */
data class CardSource(
    val type: CardType,
    val priority: Int,
    val minIntervalDays: Int?,
    val dataReady: Boolean
)
