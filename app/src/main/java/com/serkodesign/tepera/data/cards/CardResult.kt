package com.serkodesign.tepera.data.cards

/**
 * T-13: "результат (показано / пропущено / відповіли)" — третій рівень рушія, історія показів.
 * [SHOWN] записується щоразу, коли картка реально потрапляє у видиму множину (не частіше разу на
 * календарний день на тип — [com.serkodesign.tepera.data.repository.CardHistoryRepository]), і
 * використовується лише для перевірки "чи вже показувалась картка-оцінка цього тижня" —
 * [ANSWERED]/[SKIPPED] записуються при явному закритті картки (кнопки "Гаразд"/"Можна
 * пропустити") і використовуються для мінімального інтервалу повтору конкретного типу.
 */
enum class CardResult { SHOWN, SKIPPED, ANSWERED }
